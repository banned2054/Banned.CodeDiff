// Generates tests/Banned.CodeDiff.Tests/DemoData.cs from the repository's own demo
// fixture (ui/vue-example/src/data.ts). Run: node gen-demodata.mjs
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const gdvRepo = resolve(process.env.GDV_REPO ?? "C:/Code/JavaScript/git-diff-view");

const entry = `
import * as demo from "${gdvRepo.replaceAll("\\", "/")}/ui/vue-example/src/data";
const out = {};
for (const k of Object.keys(demo)) {
  const d = demo[k];
  out[k] = {
    oldFileName: d.oldFile?.fileName ?? null,
    oldFileContent: d.oldFile?.content ?? null,
    newFileName: d.newFile?.fileName ?? null,
    newFileContent: d.newFile?.content ?? null,
    hunks: d.hunks ?? [],
  };
}
process.stdout.write(JSON.stringify(out));
`;

mkdirSync(join(here, "out"), { recursive: true });
await build({
  stdin: { contents: entry, resolveDir: here, loader: "ts" },
  bundle: true,
  platform: "node",
  format: "cjs",
  outfile: join(here, "out/demodata.cjs"),
  logLevel: "warning",
});

const json = execFileSync(process.execPath, [join(here, "out/demodata.cjs")], {
  maxBuffer: 1024 * 1024 * 64,
  encoding: "utf8",
});

const data = JSON.parse(json);

const csLiteral = (s) => JSON.stringify(s ?? null).replace(/^"(.*)"$/s, '"$1"');

let cs = `// <auto-generated filename="DemoData.cs" />
// Generated by tests/js-harness/gen-demodata.mjs from
// git-diff-view ui/vue-example/src/data.ts — do not edit by hand.

namespace Banned.CodeDiff.Tests;

/// <summary>The git-diff-view repository's own demo diff data, verbatim.</summary>
public static class DemoDataStore
{
    private static readonly IReadOnlyDictionary<string, DemoData.DemoCase> Cases = new Dictionary<string, DemoData.DemoCase>
    {
`;

for (const [name, d] of Object.entries(data)) {
  const hunks = d.hunks.map((h) => csLiteral(h)).join(",\n            ");
  cs += `        ["${name}"] = new DemoData.DemoCase(
            ${csLiteral(d.oldFileName)} ?? "",
            ${csLiteral(d.oldFileContent)} ?? "",
            ${csLiteral(d.newFileName)} ?? "",
            ${csLiteral(d.newFileContent)} ?? "",
            new[]
            {
            ${hunks}
            }
        ),
`;
}

cs += `    };

    public static DemoData.DemoCase Get(string name)
    {
        return Cases.TryGetValue(name, out var c)
            ? c
            : throw new InvalidOperationException($"unknown demo case {name}");
    }
}
`;

const outPath = join(here, "..", "Banned.CodeDiff.Tests", "DemoData.cs");
writeFileSync(outPath, cs);
console.log("DemoData.cs written:", outPath, `${(cs.length / 1024).toFixed(0)} KB`);
